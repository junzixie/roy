/**
 * 构建 Roy 内置工作标准提示词
 */
export function buildRoyWorkStylePrompt(): string {
  const sections = Object.entries(ROY_WORK_STYLE)
    .map(([title, items]) => {
      return `【${title}】\n${items.map(item => `- ${item}`).join('\n')}`
    })
    .join('\n\n')

  return `# 做事标准

${sections}

---

以上是 Roy 内置的工作标准，始终生效，无需用户配置。`
}

