/** 版本号比较：a > b 返回正数。只比较数字段，忽略预发布后缀。 */
export function compareVersions(a: string, b: string): number {
  const pa = a.split(/[.-]/).map((x) => Number.parseInt(x, 10) || 0)
  const pb = b.split(/[.-]/).map((x) => Number.parseInt(x, 10) || 0)
  for (let i = 0; i < Math.max(pa.length, pb.length, 3); i++) {
    const diff = (pa[i] ?? 0) - (pb[i] ?? 0)
    if (diff !== 0) return diff
  }
  return 0
}

/**
 * 升级后要展示的更新说明：从上次看过的版本（不含）到当前版本（含）之间的条目，新的在前。
 * 没看过任何版本（全新安装）时返回空，由新手引导接手。
 */
export function changelogSince(lastSeen: string | undefined, current: string, entries: ChangelogEntry[] = CHANGELOG): ChangelogEntry[] {
  if (!lastSeen) return []
  if (compareVersions(current, lastSeen) <= 0) return []
  return entries
    .filter((entry) => compareVersions(entry.version, lastSeen) > 0 && compareVersions(entry.version, current) <= 0)
    .sort((a, b) => compareVersions(b.version, a.version))
}
