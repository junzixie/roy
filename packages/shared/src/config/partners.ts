function cleanText(value: unknown, max: number): string {
  return typeof value === 'string' ? value.trim().slice(0, max) : ''
}
function normalizeCustomPartner(value: unknown): PartnerDefinition | undefined {
  if (!value || typeof value !== 'object') return undefined
  const raw = value as Partial<PartnerDefinition>
  const id = cleanText(raw.id, 80)
  const name = cleanText(raw.name, 40)
  const prompt = cleanText(raw.prompt, 8000)
  if (!/^custom-[a-zA-Z0-9-]+$/.test(id) || !name || !prompt) return undefined
  const list = (items: unknown, max: number): string[] => Array.isArray(items) ? items.map(x => cleanText(x, 80)).filter(Boolean).slice(0, max) : []
  return { id, name, prompt, category: '我的伙伴', icon: cleanText(raw.icon, 12) || name.slice(0, 1), title: cleanText(raw.title, 80) || '自定义伙伴', description: cleanText(raw.description, 240) || cleanText(raw.title, 80) || '自定义伙伴', tags: list(raw.tags, 8), skillIds: [...new Set(list(raw.skillIds, 16))].filter(id => /^[a-zA-Z0-9][a-zA-Z0-9_.-]*$/.test(id)), examples: list(raw.examples, 8) }
}
export function getPartner(id: string | undefined, custom: readonly PartnerDefinition[] = []): PartnerDefinition | undefined {
  if (!id) return undefined
  return PARTNER_CATALOG.find((p) => p.id === id) ?? custom.find((p) => p.id === id)
}

export function normalizePartnerSettings(input: unknown): PartnerSettings {
  const raw = (input && typeof input === 'object' ? input : {}) as Partial<PartnerSettings>
  const custom = Array.isArray(raw.custom) ? raw.custom.map(normalizeCustomPartner).filter((p): p is PartnerDefinition => !!p).filter((p, i, all) => all.findIndex(x => x.id === p.id) === i).slice(0, 100) : []
  const known = new Set([...PARTNER_CATALOG.map((p) => p.id), ...custom.map((p) => p.id)])
  const installed = Array.isArray(raw.installed) ? [...new Set(raw.installed.filter((id): id is string => typeof id === 'string' && known.has(id)))] : []
  const disabled = Array.isArray(raw.disabled) ? raw.disabled.filter((id): id is string => typeof id === 'string' && installed.includes(id)) : []
  const active = typeof raw.active === 'string' && installed.includes(raw.active) && !disabled.includes(raw.active) ? raw.active : undefined
  return { installed, disabled, ...(active ? { active } : {}), ...(custom.length ? { custom } : {}) }
}

/** 返回当前生效伙伴的系统提示词片段；没有选中或已停用时返回空串。 */
export function buildActivePartnerPromptSection(input: unknown): string {
  const settings = normalizePartnerSettings(input)
  const partner = getPartner(settings.active, settings.custom)
  if (!partner) return ''
  return `\n\n## 当前工作伙伴：${partner.name}\n\n用户在输入框里选择了工作伙伴「${partner.name}」（${partner.title}）。在不违反上面规则的前提下，按下面的人设和做事方式完成任务：\n\n${partner.prompt.slice(0, 8000)}`
}

/** 仅供用户主动聊天使用；执行器仍按原技能权限加载。 */
export function getActivePartnerSkillIds(input: unknown): string[] {
  const settings = normalizePartnerSettings(input)
  return getPartner(settings.active, settings.custom)?.skillIds ?? []
}
